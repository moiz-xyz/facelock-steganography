LICENCE_KODAK = "Kodak Lossless True Color Image Suite - released by Eastman Kodak for unrestricted research use"
LICENCE_SIPI = "USC-SIPI Image Database - free for research use; copyright status per image unverified (see README)"
LICENCE_SYN = "Synthetic - generated by this script, public domain (CC0)"


def fetch(url: str, dest: Path) -> bytes:
    if dest.exists() and dest.stat().st_size > 1000:
        return dest.read_bytes()
    dest.parent.mkdir(parents=True, exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (research dataset builder)"})
    data = urllib.request.urlopen(req, timeout=60).read()
    if data[:15].lower().startswith(b"<!doctype") or data[:5].lower() == b"<html":
        raise IOError(f"server returned HTML for {url}")
    dest.write_bytes(data)
    return data


def to_rgb8(img: Image.Image) -> Image.Image:
    """Convert any PIL mode (incl. 16-bit) to 8-bit RGB."""
    if img.mode in ("I;16", "I;16B", "I"):
        arr = np.asarray(img, dtype=np.float64)
        arr = (arr / max(arr.max(), 1) * 255).astype(np.uint8)
        img = Image.fromarray(arr)
    if img.mode == "RGB" and img.getextrema() and isinstance(img.getextrema()[0], tuple):
        return img
    return img.convert("RGB")


def font(size: int) -> ImageFont.ImageFont:
    for name in ("DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "arial.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


WORDS = ("the system data image secure key face vault cipher pixel channel random hidden message report "
         "analysis network protocol access control signal entropy matrix sample model verify encrypt "
         "authentic integrity session server client password token audit record threshold result method "
         "design module layer stream process quality review project team budget meeting schedule").split()


def lorem(n_chars: int, seed: int) -> str:
    rng = np.random.default_rng(seed)
    out, line = [], 0
    while sum(len(w) + 1 for w in out) < n_chars:
        w = WORDS[rng.integers(len(WORDS))]
        if line == 0:
            w = w.capitalize()
        out.append(w)
        line += 1
        if line > rng.integers(8, 16):
            out[-1] += "."
            line = 0
    return " ".join(out)


def synthetic_covers() -> list[tuple[str, Image.Image, str]]:
    rng = np.random.default_rng(42)
    res = []
    # 1. text-heavy document page
    page = Image.new("RGB", (1000, 1400), (250, 250, 246))
    d = ImageDraw.Draw(page)
    d.text((70, 60), "CONFIDENTIAL - Quarterly Security Review", fill=(20, 20, 60), font=font(34))
    y, f = 140, font(19)
    text = lorem(9000, 1)
    words, line = text.split(), ""
    for w in words:
        if d.textlength(line + " " + w, font=f) > 860:
            d.text((70, y), line, fill=(30, 30, 30), font=f)
            y += 30
            line = w
            if y > 1330:
                break
        else:
            line = (line + " " + w).strip()
    res.append(("syn_text_document.png", page, "text-heavy"))
    # 2. UI screenshot 1920x1080
    ui = Image.new("RGB", (1920, 1080), (18, 22, 33))
    d = ImageDraw.Draw(ui)
    d.rectangle([0, 0, 280, 1080], fill=(26, 31, 46))
    for i in range(9):
        d.rounded_rectangle([24, 110 + i * 70, 256, 160 + i * 70], 10, fill=(40, 48, 70) if i else (60, 90, 200))
        d.text((44, 122 + i * 70), f"Menu item {i + 1}", fill=(220, 225, 240), font=font(20))
    for r in range(2):
        for c in range(3):
            x0, y0 = 330 + c * 520, 110 + r * 470
            d.rounded_rectangle([x0, y0, x0 + 490, y0 + 440], 18, fill=(30, 36, 54))
            d.text((x0 + 26, y0 + 22), f"Widget {r * 3 + c + 1}", fill=(235, 238, 245), font=font(26))
            pts = np.cumsum(rng.normal(0, 12, 40)) + 250
            xy = [(x0 + 30 + i * 11, y0 + 120 + int(p) % 280) for i, p in enumerate(pts)]
            d.line(xy, fill=(90, 160, 255), width=3)
    d.text((330, 40), "FaceLock Monitoring Console", fill=(255, 255, 255), font=font(34))
    res.append(("syn_ui_screenshot_1920x1080.png", ui, "screenshot/flat-UI"))
    # 3. flat low-detail (almost uniform) - worst case for LSB
    flat = np.full((600, 800, 3), (120, 160, 210), np.uint8)
    flat[400:] = (90, 130, 80)
    res.append(("syn_flat_lowdetail.png", Image.fromarray(flat), "low-detail/flat"))
    # 4. smooth gradient sky
    y, x = np.mgrid[0:720, 0:1280].astype(np.float64)
    grad = np.stack([40 + x / 1280 * 120, 90 + y / 720 * 100, 200 - y / 720 * 60], -1)
    res.append(("syn_gradient_1280x720.png", Image.fromarray(grad.astype(np.uint8)), "low-detail/gradient"))
    # 5. geometric pattern
    g = Image.new("RGB", (512, 512), "white")
    d = ImageDraw.Draw(g)
    for i in range(0, 512, 32):
        for j in range(0, 512, 32):
            if (i // 32 + j // 32) % 2:
                d.rectangle([i, j, i + 31, j + 31], fill=(30, 30, 30))
    for k in range(12):
        d.ellipse([256 - 20 * k, 256 - 20 * k, 256 + 20 * k, 256 + 20 * k], outline=(220, 40, 40), width=3)
    res.append(("syn_geometric_512.png", g, "geometric/synthetic"))
    # 6. natural-noise texture (fractal-like)
    noise = np.zeros((480, 640))
    for octave in range(1, 7):
        small = rng.random((480 // 2 ** (6 - octave) + 1, 640 // 2 ** (6 - octave) + 1))
        noise += np.asarray(Image.fromarray((small * 255).astype(np.uint8)).resize((640, 480), Image.BICUBIC)) / octave
    noise = (noise - noise.min()) / np.ptp(noise)
    tex = np.stack([noise * 160 + 60, noise * 120 + 50, noise * 80 + 30], -1).astype(np.uint8)
    res.append(("syn_noise_texture_640x480.png", Image.fromarray(tex).filter(ImageFilter.SMOOTH), "texture/noise"))
    return res


def make_pdf(path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages
    with PdfPages(path) as pdf:
        for page in range(2):
            fig = plt.figure(figsize=(8.27, 11.69))
            fig.text(0.08, 0.94, f"CONFIDENTIAL MEMO - page {page + 1}", fontsize=16, weight="bold")
            body = lorem(2600, 10 + page)
            lines, cur = [], ""
            for w in body.split():
                if len(cur) + len(w) > 92:
                    lines.append(cur); cur = w
                else:
                    cur = (cur + " " + w).strip()
            lines.append(cur)
            for i, ln in enumerate(lines[:40]):
                fig.text(0.08, 0.89 - i * 0.02, ln, fontsize=9, family="serif")
            if page == 0:
                ax = fig.add_axes([0.1, 0.06, 0.8, 0.12])
                ax.bar(range(8), np.random.default_rng(3).integers(10, 90, 8), color="#3b6fd8")
                ax.set_title("Incidents per week (sample data)", fontsize=9)
            pdf.savefig(fig)
            plt.close(fig)


def main() -> int:
    COVERS.mkdir(parents=True, exist_ok=True)
    PAYLOADS.mkdir(parents=True, exist_ok=True)
    rows = []
    # Kodak
    for i in range(1, 25):
        try:
            data = fetch(KODAK_URL.format(i), RAW / "kodak" / f"kodim{i:02d}.png")
        except Exception as exc:  # noqa: BLE001
            print("skip kodak", i, exc); continue
        img = to_rgb8(Image.open(io.BytesIO(data)))
        out = COVERS / "kodak" / f"kodim{i:02d}.png"
        out.parent.mkdir(exist_ok=True)
        img.save(out)
        rows.append([f"covers/kodak/{out.name}", "Kodak PhotoCD (kodim%02d)" % i, KODAK_CAT[i], *img.size, LICENCE_KODAK])
    # USC-SIPI
    for img_id, (vol, name, cat) in SIPI.items():
        try:
            data = fetch(SIPI_URL.format(vol=vol, img=img_id), RAW / "sipi" / f"{img_id}.tiff")
        except Exception as exc:  # noqa: BLE001
            print("skip sipi", img_id, exc); continue
        img = to_rgb8(Image.open(io.BytesIO(data)))
        out = COVERS / "sipi" / f"sipi_{img_id.replace('.', '_')}.png"
        out.parent.mkdir(exist_ok=True)
        img.save(out)
        rows.append([f"covers/sipi/{out.name}", f"USC-SIPI {img_id} ({name})", cat, *img.size, LICENCE_SIPI])
    # Synthetic
    (COVERS / "synthetic").mkdir(exist_ok=True)
    for fname, img, cat in synthetic_covers():
        img.save(COVERS / "synthetic" / fname)
        rows.append([f"covers/synthetic/{fname}", "Generated (scripts/build_dataset.py)", cat, *img.size, LICENCE_SYN])

    with open(DS / "manifest.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["file", "source", "category", "width", "height", "licence"])
        w.writerows(rows)

    # Payloads
    for label, n in (("100B", 100), ("1KB", 1024), ("10KB", 10 * 1024), ("50KB", 50 * 1024)):
        txt = lorem(n + 200, seed=n).encode("ascii")[:n]
        (PAYLOADS / f"payload_{label}.txt").write_bytes(txt)
    make_pdf(PAYLOADS / "sample_memo.pdf")
    print(f"{len(rows)} cover images, payloads: {sorted(p.name for p in PAYLOADS.iterdir())}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
